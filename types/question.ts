/**
 * types/question.ts
 * ---------------------------------------------------------------------------
 * ไฟล์ใหม่ — Data Model ของระบบ "ภารกิจ + คำถามประจำฐาน (เผ่า)" ตาม Flow ใหม่
 *
 *   Scan QR เข้าฐาน -> แสดงภารกิจของฐานนั้น -> ลูกค้าปฏิบัติตามภารกิจ ->
 *   ตอบคำถามบนระบบ (1 คำถาม 1 คำตอบ) -> ถูก = ได้คะแนน / ผิด = ไม่ได้คะแนน ->
 *   เดินทางไปเผ่าต่อไป
 *
 * กติกาที่ตกลงกันไว้ (มีผลต่อ type ในไฟล์นี้โดยตรง):
 *   - คะแนนได้ "ทั้ง" ตอนสแกนเข้าฐาน (แต้มฐาน — ระบบเดิม useAdventure/checkin)
 *     "และ" ตอนตอบคำถามถูก (แต้มคำถาม — ระบบใหม่ในไฟล์นี้) แยกกันคนละก้อน
 *     ไม่ปนกัน เพื่อให้ยังดูย้อนหลังได้ว่าแต้มมาจากไหน
 *   - ตอบได้ครั้งเดียวต่อ 1 คำถาม ผิดแล้วผิดเลย (ดู StationAnswer.locked)
 *
 * เจตนาออกแบบเหมือน types/photoQuest.ts: "เนื้อหาของคำถาม" ทั้งหมดมาจาก
 * Google Sheet ("Questions" ผ่าน server-gas/QuestionService.gs) ห้าม hard-code
 * คำถาม/คำตอบใด ๆ ไว้ในโค้ด frontend เด็ดขาด
 */

/** รูปแบบการตอบคำถาม — เพิ่มชนิดใหม่ได้โดยไม่กระทบโครงสร้างหลัก */
export type AnswerType =
  | 'choice' // ปรนัย เลือก 1 ข้อจาก choices
  | 'text' // อัตนัยสั้น ๆ พิมพ์ตอบ (เทียบแบบ normalize แล้ว)
  | 'number' // ตัวเลข (เทียบค่าเท่ากัน ไม่สนรูปแบบการพิมพ์)

/** 1 คำถามประจำฐาน (ชีต "Questions") */
export interface StationQuestion {
  id: string
  /** ผูกกับฐานไหน — ตรงกับ Stations.Id (เช่น 'corn' / 'cow' / 'milk' / 'soil') */
  stationId: string
  /** ข้อความภารกิจที่ให้ลูกค้าไปทำก่อนตอบ (เช่น "ตามหาความหอมของแต่ละเผ่า") */
  mission: string
  /** ตัวคำถามที่ต้องตอบบนระบบ */
  question: string
  answerType: AnswerType
  /** ตัวเลือก (ใช้เฉพาะ answerType === 'choice') */
  choices: string[]
  /** เฉลย — ดูหมายเหตุเรื่อง Offline First ด้านล่างของไฟล์นี้ */
  correctAnswer: string
  /** คะแนนที่ได้ถ้าตอบถูก (คนละก้อนกับแต้มของฐาน) */
  points: number
  active: boolean
  /** คำอธิบาย/เฉลยแบบยาว แสดงหลังตอบแล้ว (ไม่บังคับ) */
  explanation?: string
  order?: number
  updatedAt?: string
}

/** ผลการตอบคำถาม 1 ครั้งของผู้เล่น 1 คน — เก็บใน LocalStorage ก่อนเสมอ
 * (Offline First เหมือน PendingCheckin/PhotoQuestAttempt ของระบบเดิม) */
export interface StationAnswer {
  /** uuid ฝั่ง client — กันบันทึกซ้ำตอน sync เหมือน PendingCheckin.uuid */
  clientId: string
  questionId: string
  stationId: string
  /** roundId ของรอบที่ตอบ — ใช้แยกว่าแต้มนี้เป็นของรอบไหน */
  roundId: string | null
  /** คำตอบที่ผู้เล่นเลือก/พิมพ์จริง (เก็บไว้ดูย้อนหลังได้) */
  answer: string
  isCorrect: boolean
  /** แต้มที่ได้จริงจากข้อนี้ (0 ถ้าตอบผิด) */
  pointsEarned: number
  answeredAt: number
  synced: boolean
  /** true เสมอหลังตอบ 1 ครั้ง — ตอกย้ำกติกา "ตอบได้ครั้งเดียว ผิดแล้วผิดเลย"
   * ฝั่ง UI ใช้ค่านี้ปิดปุ่มตอบทันที ไม่ต้องไปคำนวณเงื่อนไขเองหลายที่ */
  locked: true
}

/** สรุปผลคำถามของทั้งรอบ — ใช้แสดงที่หน้าสรุปคะแนน */
export interface QuestionRoundSummary {
  totalAnswered: number
  totalCorrect: number
  totalQuestionPoints: number
}

